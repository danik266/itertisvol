/** Буквы, которых нет в русском алфавите, — верный признак казахского текста. */
const KAZAKH_LETTERS = /[әғқңөұүһі]/i;

/**
 * Каким голосом читать текст.
 *
 * Язык страницы — не всё: помощник отвечает на языке вопроса, и в русском
 * режиме на казахскую фразу он ответит по-казахски. Поэтому сначала смотрим
 * на сам текст, а язык интерфейса берём как второй признак.
 */
export function speechLang(text: string, pageLang?: string): 'kk' | 'ru' {
  if (KAZAKH_LETTERS.test(text)) return 'kk';
  return pageLang === 'kz' || pageLang === 'kk' ? 'kk' : 'ru';
}

/**
 * Синтезаторы проговаривают эмодзи и разметку вслух («подмигивающее лицо»,
 * «звёздочка»), поэтому в озвучку они не попадают. В переписке текст остаётся
 * как есть.
 */
export function forSpeech(raw: string): string {
  return String(raw)
    .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE00}-\u{FE0F}\u{1F1E6}-\u{1F1FF}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}\u{20D0}-\u{20FF}\u{2122}\u{2139}\u{3030}\u{303D}]/gu, ' ')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[*_`#~|]/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
}
