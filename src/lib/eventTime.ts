/**
 * Время начала мероприятия хранится строкой «ЧЧ:ММ» рядом с датой.
 *
 * Класть его внутрь Date нельзя: база держит даты в UTC, и указанные
 * организатором 18:00 показались бы волонтёру как 13:00. Строка же means
 * ровно то, что человек ввёл, а пустое значение — что время не указали.
 */
export function cleanTime(value: unknown): string {
  const time = String(value || '').trim();
  return /^([01]\d|2[0-3]):[0-5]\d$/.test(time) ? time : '';
}
